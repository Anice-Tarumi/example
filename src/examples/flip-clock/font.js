export const GLYPH_W = 5
export const GLYPH_H = 7

/** コロンと句読点は詰める。等幅のままだと字間が空いて読みにくい */
const NARROW = { ':': 3, '.': 3, ' ': 3 }

export function glyphWidth(ch) {
  return NARROW[ch] ?? GLYPH_W
}

export function measure(text, spacing = 1) {
  let w = 0
  for (const ch of text) w += glyphWidth(ch) + spacing
  return Math.max(0, w - spacing)
}

/**
 * 文字列を盤のビットへ焼く。
 *
 * 盤の大きさは呼び手が決める。文字が入りきらない場合は左から切る。
 * 盤を文字に合わせて作り直すと、桁が変わるたびに全部が組み直しになる。
 */
export function stampText(bits, cols, rows, text, { spacing = 1, ox = null, oy = null } = {}) {
  const w = measure(text, spacing)
  let x = ox ?? Math.floor((cols - w) / 2)
  const y0 = oy ?? Math.floor((rows - GLYPH_H) / 2)

  for (const ch of text) {
    const rowsOf = G[ch] ?? G[' ']
    const gw = glyphWidth(ch)
    // 詰める字は中央から切り出す
    const off = Math.floor((GLYPH_W - gw) / 2)
    for (let gy = 0; gy < GLYPH_H; gy++) {
      const line = rowsOf[gy]
      for (let gx = 0; gx < gw; gx++) {
        if (line[gx + off] !== '1') continue
        const px = x + gx
        const py = y0 + gy
        if (px < 0 || py < 0 || px >= cols || py >= rows) continue
        // 上が行 0 になるよう y を反転して詰める
        bits[(rows - 1 - py) * cols + px] = 1
      }
    }
    x += gw + spacing
  }
  return bits
}
